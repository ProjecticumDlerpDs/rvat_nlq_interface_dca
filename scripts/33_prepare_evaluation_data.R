# ------------------------------------------------------------
# 33_prepare_evaluation_data.R
#
# PURPOSE
# -------
# Transform a raw benchmark capture produced by
# 32_run_raw_data_capture.R into an evaluation-ready CSV.
#
# RESPONSIBILITIES
# ----------------
# - Read one raw .rds capture
# - Validate the raw-data structure
# - Read the authoritative benchmark specification
# - Remove empty benchmark rows
# - Construct stable question identifiers
# - Join benchmark metadata using question_id
# - Preserve all raw production measurements
# - Add blank EM and EX fields for manual evaluation
# - Export the derived dataset to data/processed/
#
# RESEARCH DATA BOUNDARY
# ----------------------
# data/raw/
#   Immutable observed data generated by 32_
#
# data/processed/
#   Derived evaluation template generated by 33_
#
# data/analysis/
#   Manually evaluated dataset with EM / EX scores
#
# IMPORTANT
# ---------
# - Raw .rds files are never modified
# - Benchmark metadata are joined by question_id
# - Row order and NLQ text are not used as join keys
# - EM and EX are NOT calculated automatically
# ------------------------------------------------------------


library(here)
library(readr)


# ------------------------------------------------------------
# CONFIGURATION
# ------------------------------------------------------------

BENCHMARK_FILE <- here(
  "data",
  "benchmark_questions.csv"
)

# DEVELOPMENT INPUT
#
# Replace this filename with the raw capture that should
# be prepared for evaluation.
#
# For current development this may point to the recovery
# artifact. Final research processing must use a validated
# raw capture produced by 32_.

RAW_CAPTURE_FILE <- here(
  "data",
  "raw",
  "raw_capture_qwen2.5-coder_latest_full_gdb_recovery_test.rds"
)


# ------------------------------------------------------------
# VALIDATE INPUT FILES
# ------------------------------------------------------------

if (!file.exists(RAW_CAPTURE_FILE)) {
  stop(
    "Raw capture file not found: ",
    RAW_CAPTURE_FILE
  )
}

if (!file.exists(BENCHMARK_FILE)) {
  stop(
    "Benchmark file not found: ",
    BENCHMARK_FILE
  )
}


# ------------------------------------------------------------
# LOAD RAW CAPTURE
# ------------------------------------------------------------

raw_capture <- tryCatch(
  readRDS(RAW_CAPTURE_FILE),
  error = function(e) {
    stop(
      "Unable to read raw capture RDS: ",
      e$message
    )
  }
)

if (!is.data.frame(raw_capture)) {
  stop(
    "Raw capture is not a data.frame."
  )
}


# ------------------------------------------------------------
# VALIDATE REQUIRED RAW FIELDS
# ------------------------------------------------------------

required_raw_columns <- c(
  "question_id",
  "run_id",
  "db_mode",
  "timestamp",
  "user_query",
  "sql_query",
  "prompt_tokens",
  "generated_tokens",
  "rows_returned",
  "result_preview",
  "status",
  "error_message",
  "model",
  "model_parameters",
  "model_capability",
  "model_temperature",
  "time_total_sec"
)

missing_raw_columns <- setdiff(
  required_raw_columns,
  names(raw_capture)
)

if (length(missing_raw_columns) > 0) {
  stop(
    "Raw capture is missing required column(s): ",
    paste(
      missing_raw_columns,
      collapse = ", "
    )
  )
}


# ------------------------------------------------------------
# VALIDATE RAW EXPERIMENTAL IDENTIFIERS
# ------------------------------------------------------------

if (anyNA(raw_capture$question_id)) {
  stop(
    "Raw capture contains missing question_id values."
  )
}

if (anyNA(raw_capture$run_id)) {
  stop(
    "Raw capture contains missing run_id values."
  )
}

if (anyNA(raw_capture$db_mode)) {
  stop(
    "Raw capture contains missing db_mode values."
  )
}

raw_keys <- paste(
  raw_capture$question_id,
  raw_capture$run_id,
  sep = "::"
)

if (anyDuplicated(raw_keys)) {
  stop(
    "Duplicate question_id/run_id combinations found ",
    "in raw capture."
  )
}


# ------------------------------------------------------------
# LOAD BENCHMARK SPECIFICATION
# ------------------------------------------------------------

benchmark <- read.csv2(
  BENCHMARK_FILE,
  stringsAsFactors = FALSE,
  check.names = FALSE
)


# ------------------------------------------------------------
# VALIDATE BENCHMARK SCHEMA
# ------------------------------------------------------------

required_benchmark_columns <- c(
  "Question number",
  "Type",
  "NLQ",
  "Expected query",
  "Expected answer",
  "Notes"
)

missing_benchmark_columns <- setdiff(
  required_benchmark_columns,
  names(benchmark)
)

if (length(missing_benchmark_columns) > 0) {
  stop(
    "Benchmark file is missing required column(s): ",
    paste(
      missing_benchmark_columns,
      collapse = ", "
    )
  )
}


# ------------------------------------------------------------
# REMOVE EMPTY BENCHMARK ROWS
# ------------------------------------------------------------

valid_question_number <- !is.na(
  benchmark[["Question number"]]
)

valid_nlq <- !is.na(
  benchmark[["NLQ"]]
) &
  nzchar(
    trimws(
      benchmark[["NLQ"]]
    )
  )

benchmark <- benchmark[
  valid_question_number & valid_nlq,
  ,
  drop = FALSE
]

rownames(benchmark) <- NULL

if (nrow(benchmark) == 0) {
  stop(
    "No valid benchmark questions remain after filtering."
  )
}


# ------------------------------------------------------------
# VALIDATE QUESTION NUMBERS
# ------------------------------------------------------------

question_numbers <- suppressWarnings(
  as.integer(
    benchmark[["Question number"]]
  )
)

if (anyNA(question_numbers)) {
  stop(
    "Benchmark contains invalid Question number values."
  )
}

if (anyDuplicated(question_numbers)) {
  stop(
    "Duplicate Question number values found in benchmark."
  )
}


# ------------------------------------------------------------
# CREATE STABLE QUESTION IDENTIFIERS
# ------------------------------------------------------------

benchmark$question_id <- sprintf(
  "Q%02d",
  question_numbers
)


# ------------------------------------------------------------
# VALIDATE RAW QUESTIONS AGAINST BENCHMARK
# ------------------------------------------------------------

unknown_question_ids <- setdiff(
  unique(raw_capture$question_id),
  benchmark$question_id
)

if (length(unknown_question_ids) > 0) {
  stop(
    "Raw capture contains question_id values not present ",
    "in benchmark_questions.csv: ",
    paste(
      unknown_question_ids,
      collapse = ", "
    )
  )
}


# ------------------------------------------------------------
# PREPARE BENCHMARK METADATA
# ------------------------------------------------------------

benchmark_metadata <- data.frame(
  question_id = benchmark$question_id,
  question_type = benchmark[["Type"]],
  expected_query = benchmark[["Expected query"]],
  expected_answer = benchmark[["Expected answer"]],
  notes = benchmark[["Notes"]],
  stringsAsFactors = FALSE
)


# ------------------------------------------------------------
# JOIN RAW CAPTURE TO BENCHMARK METADATA
# ------------------------------------------------------------
#
# match() is used deliberately so that:
# - every raw observation is preserved
# - original raw observation order is preserved
# - benchmark questions absent from the raw capture do not
#   create extra observations
# ------------------------------------------------------------

benchmark_match <- match(
  raw_capture$question_id,
  benchmark_metadata$question_id
)

if (anyNA(benchmark_match)) {
  stop(
    "One or more raw observations could not be matched ",
    "to the benchmark specification."
  )
}

evaluation_data <- raw_capture

evaluation_data$question_type <-
  benchmark_metadata$question_type[
    benchmark_match
  ]

evaluation_data$expected_query <-
  benchmark_metadata$expected_query[
    benchmark_match
  ]

evaluation_data$expected_answer <-
  benchmark_metadata$expected_answer[
    benchmark_match
  ]

evaluation_data$notes <-
  benchmark_metadata$notes[
    benchmark_match
  ]


# ------------------------------------------------------------
# ADD MANUAL EVALUATION FIELDS
# ------------------------------------------------------------
#
# Integer NA values are intentional.
#
# EM and EX must remain unscored until manual evaluation.
# Expected final values:
# 1 = pass
# 0 = fail
# ------------------------------------------------------------

evaluation_data$EM <- NA_integer_
evaluation_data$EX <- NA_integer_


# ------------------------------------------------------------
# ARRANGE EVALUATION COLUMNS
# ------------------------------------------------------------

preferred_columns <- c(
  "question_id",
  "run_id",
  "question_type",
  "db_mode",
  "timestamp",
  "user_query",
  "expected_query",
  "sql_query",
  "expected_answer",
  "result_preview",
  "notes",
  "EM",
  "EX",
  "status",
  "error_message",
  "rows_returned",
  "model",
  "model_parameters",
  "model_capability",
  "model_temperature",
  "prompt_tokens",
  "generated_tokens",
  "time_total_sec"
)

evaluation_data <- evaluation_data[
  ,
  c(
    preferred_columns,
    setdiff(
      names(evaluation_data),
      preferred_columns
    )
  ),
  drop = FALSE
]


# ------------------------------------------------------------
# VALIDATE TRANSFORMATION
# ------------------------------------------------------------

if (nrow(evaluation_data) != nrow(raw_capture)) {
  stop(
    "Processed row count does not match raw capture."
  )
}

if (!identical(
  evaluation_data$question_id,
  raw_capture$question_id
)) {
  stop(
    "question_id order changed during processing."
  )
}

if (!identical(
  evaluation_data$run_id,
  raw_capture$run_id
)) {
  stop(
    "run_id order changed during processing."
  )
}

if (anyNA(evaluation_data$question_type)) {
  stop(
    "Missing question_type after benchmark join."
  )
}


# ------------------------------------------------------------
# PREPARE OUTPUT DIRECTORY
# ------------------------------------------------------------

dir.create(
  here(
    "data",
    "processed"
  ),
  recursive = TRUE,
  showWarnings = FALSE
)


# ------------------------------------------------------------
# BUILD OUTPUT FILE NAME
# ------------------------------------------------------------

input_name <- tools::file_path_sans_ext(
  basename(
    RAW_CAPTURE_FILE
  )
)

output_file <- here(
  "data",
  "processed",
  paste0(
    input_name,
    "_evaluation_template.csv"
  )
)


# ------------------------------------------------------------
# WRITE PROCESSED EVALUATION TEMPLATE
# ------------------------------------------------------------

readr::write_csv(
  evaluation_data,
  output_file,
  na = ""
)


# ------------------------------------------------------------
# VERIFY OUTPUT FILE
# ------------------------------------------------------------

if (!file.exists(output_file)) {
  stop(
    "Processed CSV was not created: ",
    output_file
  )
}


# ------------------------------------------------------------
# READ-BACK VALIDATION
# ------------------------------------------------------------

verification_data <- readr::read_csv(
  output_file,
  show_col_types = FALSE
)

if (nrow(verification_data) != nrow(evaluation_data)) {
  stop(
    "Processed CSV integrity check failed: ",
    "row count differs after read-back."
  )
}

if (!identical(
  verification_data$question_id,
  evaluation_data$question_id
)) {
  stop(
    "Processed CSV integrity check failed: ",
    "question_id changed during export."
  )
}


# ------------------------------------------------------------
# FINAL REPORT
# ------------------------------------------------------------

cat("\n=========================================\n")
cat("EVALUATION DATA PREPARATION COMPLETED\n")
cat("=========================================\n")

cat(
  "Raw observations:",
  nrow(raw_capture),
  "\n"
)

cat(
  "Benchmark questions available:",
  nrow(benchmark),
  "\n"
)

cat(
  "Question IDs represented:",
  paste(
    unique(evaluation_data$question_id),
    collapse = ", "
  ),
  "\n"
)

cat(
  "EM populated:",
  sum(!is.na(evaluation_data$EM)),
  "\n"
)

cat(
  "EX populated:",
  sum(!is.na(evaluation_data$EX)),
  "\n"
)

cat(
  "Saved:",
  output_file,
  "\n"
)

cat("=========================================\n")